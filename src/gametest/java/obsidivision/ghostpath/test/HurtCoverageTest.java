package obsidivision.ghostpath.test;

import java.io.InputStream;
import java.lang.reflect.Method;
import java.lang.reflect.Modifier;
import java.net.URL;
import java.util.ArrayList;
import java.util.Enumeration;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Set;
import java.util.TreeSet;
import java.util.jar.JarEntry;
import java.util.jar.JarFile;
import net.fabricmc.fabric.api.gametest.v1.GameTest;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.damagesource.DamageSource;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntitySpawnReason;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.entity.boss.enderdragon.EnderDragon;
import org.objectweb.asm.ClassReader;
import org.objectweb.asm.tree.AnnotationNode;
import org.objectweb.asm.tree.ClassNode;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

/**
 * Undo-log gap 3 (ruling after R4): the {@code EntityHurtMixin} target list is generated by hand from the 26.2 sources, so
 * a version update could add an {@code Entity.hurtServer} override that nobody hooks. This test finds every entity class
 * that declares a concrete {@code hurtServer(ServerLevel, DamageSource, float)} and fails if one is missing from the
 * mixin's targets. Classes come from (1) every registered entity type, built with {@code EntityType.create}, with its
 * superclasses, and the dragon's parts; (2) a scan of the Minecraft jar for every {@code Entity} subclass, which also
 * finds classes no registered type builds (the server player).
 */
public class HurtCoverageTest {
    private static final Logger LOG = LoggerFactory.getLogger("ghostpath-test");
    private static final String MIXIN = "obsidivision/ghostpath/mixin/EntityHurtMixin.class";

    /** The mixin's {@code targets}, read from its class file (the annotation has class retention). */
    static Set<String> hookedClasses() throws Exception {
        try (InputStream in = HurtCoverageTest.class.getClassLoader().getResourceAsStream(MIXIN)) {
            if (in == null) {
                throw new IllegalStateException("cannot find " + MIXIN);
            }
            ClassNode node = new ClassNode();
            new ClassReader(in).accept(node, ClassReader.SKIP_CODE);
            List<AnnotationNode> all = new ArrayList<>();
            if (node.invisibleAnnotations != null) {
                all.addAll(node.invisibleAnnotations);
            }
            if (node.visibleAnnotations != null) {
                all.addAll(node.visibleAnnotations);
            }
            for (AnnotationNode a : all) {
                if (a.desc.equals("Lorg/spongepowered/asm/mixin/Mixin;") && a.values != null) {
                    for (int i = 0; i + 1 < a.values.size(); i += 2) {
                        if (a.values.get(i).equals("targets")) {
                            Set<String> out = new TreeSet<>();
                            for (Object o : (List<?>) a.values.get(i + 1)) {
                                out.add((String) o);
                            }
                            return out;
                        }
                    }
                }
            }
        }
        throw new IllegalStateException("no @Mixin(targets) on EntityHurtMixin");
    }

    private static boolean declaresConcreteHurtServer(Class<?> c) {
        try {
            Method m = c.getDeclaredMethod("hurtServer", ServerLevel.class, DamageSource.class, float.class);
            return !Modifier.isAbstract(m.getModifiers());
        } catch (NoSuchMethodException e) {
            return false;
        }
    }

    private static void addHierarchy(Set<Class<?>> out, Class<?> c) {
        for (; c != null && Entity.class.isAssignableFrom(c); c = c.getSuperclass()) {
            out.add(c);
        }
    }

    /** Every class in the jar that holds {@code Entity} (the common jar) that is an Entity subclass. */
    private static Set<Class<?>> scanJar(List<String> problems) {
        Set<Class<?>> out = new LinkedHashSet<>();
        URL url = Entity.class.getResource("Entity.class");
        if (url == null || !url.getProtocol().equals("jar")) {
            problems.add("cannot locate the Minecraft jar from " + url);
            return out;
        }
        String path = url.getPath();
        String jarFile = path.substring(path.indexOf(':') + 1, path.indexOf("!/"));
        try (JarFile jar = new JarFile(java.net.URLDecoder.decode(jarFile, java.nio.charset.StandardCharsets.UTF_8))) {
            for (Enumeration<JarEntry> e = jar.entries(); e.hasMoreElements();) {
                String name = e.nextElement().getName();
                if (!name.startsWith("net/minecraft/") || !name.endsWith(".class")) {
                    continue;
                }
                try {
                    Class<?> c = Class.forName(name.substring(0, name.length() - 6).replace('/', '.'), false, Entity.class.getClassLoader());
                    if (Entity.class.isAssignableFrom(c)) {
                        out.add(c);
                    }
                } catch (Throwable t) {
                    // classes that cannot load on a server (client-only references) cannot be entities in a server world
                }
            }
        } catch (Exception ex) {
            problems.add("jar scan failed: " + ex);
        }
        return out;
    }

    @GameTest
    public void everyHurtServerOverrideIsHooked(GameTestHelper helper) throws Exception {
        ServerLevel level = helper.getLevel();
        Set<String> hooked = hookedClasses();
        List<String> problems = new ArrayList<>();

        Set<Class<?>> fromRegistry = new LinkedHashSet<>();
        int types = 0;
        int notBuilt = 0;
        for (EntityType<?> type : BuiltInRegistries.ENTITY_TYPE) {
            types++;
            Entity e = null;
            try {
                e = type.create(level, EntitySpawnReason.LOAD);
            } catch (Throwable t) {
                LOG.info("[ghostpath] hurt coverage: {} cannot be built here: {}", EntityType.getKey(type), t.toString());
            }
            if (e == null) {
                notBuilt++;
                continue;
            }
            addHierarchy(fromRegistry, e.getClass());
            if (e instanceof EnderDragon dragon) {
                for (Entity part : dragon.getSubEntities()) {
                    addHierarchy(fromRegistry, part.getClass());
                }
            }
        }
        Set<Class<?>> fromJar = scanJar(problems);
        Set<Class<?>> all = new LinkedHashSet<>(fromRegistry);
        all.addAll(fromJar);

        Set<String> overrides = new TreeSet<>();
        for (Class<?> c : all) {
            if (c != Entity.class && declaresConcreteHurtServer(c)) {
                overrides.add(c.getName());
            }
        }
        LOG.info("[ghostpath] hurt coverage: {} entity types ({} not built), {} classes from the registry, {} from the jar scan, {} override hurtServer, {} hooked",
            types, notBuilt, fromRegistry.size(), fromJar.size(), overrides.size(), hooked.size());

        // sanity: the scan must really have seen the known cases, or it proves nothing
        for (String must : List.of("net.minecraft.world.entity.LivingEntity", "net.minecraft.world.entity.item.PrimedTnt",
            "net.minecraft.world.entity.vehicle.minecart.MinecartTNT", "net.minecraft.server.level.ServerPlayer")) {
            helper.assertTrue(overrides.contains(must), "scan did not find the known override " + must + " (" + overrides.size() + " found); " + problems);
        }
        helper.assertTrue(fromRegistry.size() > 100, "registry scan found only " + fromRegistry.size() + " classes");
        Set<String> missing = new TreeSet<>(overrides);
        missing.removeAll(hooked);
        helper.assertTrue(missing.isEmpty(), "Entity.hurtServer overrides not in EntityHurtMixin: " + missing
            + " (add them to the targets list; see DESIGN, undo-log gaps)");
        // the other direction: a hooked class without an override would fail start-up anyway, but say it plainly
        Set<String> stale = new TreeSet<>(hooked);
        stale.removeAll(overrides);
        helper.assertTrue(stale.isEmpty(), "EntityHurtMixin targets without a hurtServer override: " + stale);
        helper.succeed();
    }
}
